from __future__ import annotations

import html
import json
import re
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

from .models import AuditResult

IMPACT_ORDER = {"High": 0, "Medium": 1, "Low": 2}
SENSITIVE_QUERY_PARTS = ("token", "key", "secret", "password", "passwd", "auth", "session", "signature", "credential", "csrf")


def redact_url(url: str) -> str:
    """Mask likely credentials in query strings before writing reports."""
    parts = urlsplit(url)
    if not parts.query:
        return url
    safe_pairs = []
    for name, value in parse_qsl(parts.query, keep_blank_values=True):
        is_sensitive = any(marker in name.lower() for marker in SENSITIVE_QUERY_PARTS)
        safe_pairs.append((name, "[REDACTED]" if is_sensitive else value))
    return urlunsplit((parts.scheme, parts.netloc, parts.path, urlencode(safe_pairs), ""))


def _redact_text(value: str) -> str:
    """Redact query secrets embedded in free-text audit notes."""
    return re.sub(r"https?://[^\s)]+", lambda match: redact_url(match.group(0)), value)


def _table_cell(value: str) -> str:
    return value.replace("\\", "\\\\").replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def _inline_code(value: str) -> str:
    return "`" + value.replace("`", "\\`").replace("\r", " ").replace("\n", " ") + "`"


def render_markdown(result: AuditResult) -> str:
    summary = result.summary
    lines = [
        "# Website Audit Report", "", f"**Target:** {_inline_code(redact_url(result.target_url))}",
        f"**Started (UTC):** {result.started_at}", f"**Pages inspected:** {len(result.pages)}", "",
        "## Executive summary", "",
        f"- **High priority:** {summary['high']}",
        f"- **Medium priority:** {summary['medium']}",
        f"- **Low priority:** {summary['low']}", "",
        "> Priority is a review heuristic. This report does not estimate revenue loss or guarantee conversion gains.", "",
        "## Findings", "",
    ]
    if not result.findings:
        lines.append("No findings were generated from the checks that ran. This does not prove the site is issue-free.")
    for index, finding in enumerate(sorted(result.findings, key=lambda item: (IMPACT_ORDER.get(item.impact, 3), item.category, item.title)), 1):
        lines.extend([
            f"### {index}. [{finding.impact} impact] {finding.title}", "",
            f"- **Category:** {finding.category}", f"- **Page:** {_inline_code(redact_url(finding.url))}",
            f"- **Confidence:** {finding.confidence}", f"- **Evidence:** {finding.evidence}",
            f"- **Why it may matter:** {finding.business_rationale}",
            f"- **Recommended action:** {finding.recommendation}",
            f"- **How to verify:** {finding.verification}", "",
        ])
    lines.extend(["## Pages inspected", "", "| URL | HTTP status | Title | Error / note |", "|---|---:|---|---|"])
    for page in result.pages:
        title = _table_cell(page.title)
        error = _table_cell(page.error)
        page_url = _table_cell(redact_url(page.url))
        lines.append(f"| {page_url} | {page.status_code if page.status_code is not None else 'Not fetched'} | {title} | {error} |")
    lines.extend(["", "## Audit notes", ""])
    lines.extend([f"- {_redact_text(note)}" for note in result.notes] or ["- No additional notes."])
    lines.extend(["", "---", "Generated by [Website Revenue Leak Auditor](https://github.com/yerageracharan/website-revenue-leak-auditor).", ""])
    return "\n".join(lines)


